import fs from "node:fs";
import path from "node:path";
import puppeteer from "puppeteer-core";
import chromium from "@sparticuz/chromium";
const BASE="http://localhost:5173";
const OUT=path.resolve("docs/phase-3-refinement/evidence/probe");
const res=await fetch(`${BASE}/api/v1/auth/staff/sign-in`,{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({identifier:"admin@pratikshya.local",password:"Admin@PF2026!"})});
const auth=await res.json();
fs.mkdirSync(OUT,{recursive:true});
const browser=await puppeteer.launch({executablePath:await chromium.executablePath(),args:[...chromium.args.filter(a=>!a.includes("single-process") || a.includes("hide-scrollbars")),"--font-render-hinting=none"],headless:true});
const page=await browser.newPage();
await page.setViewport({width:1536,height:900});
await page.goto(`${BASE}/login`,{waitUntil:"domcontentloaded"});
await page.evaluate(d=>{localStorage.setItem("pf_admin_access_token",d.access_token);localStorage.setItem("pf_admin_refresh_token",d.refresh_token);localStorage.setItem("pratikshya_admin_auth",JSON.stringify(d.admin));
  localStorage.removeItem("pf_admin_nav_groups"); localStorage.removeItem("pratikshya_admin_sidebar_collapsed");},auth);
await page.goto(`${BASE}/super-admin`,{waitUntil:"networkidle2"});
await new Promise(r=>setTimeout(r,1200));
const collapsedCount=await page.evaluate(()=>{const nav=document.querySelector("#admin-navigation"); return nav.querySelectorAll("button[aria-expanded='false']").length;});
const state=await page.evaluate(()=>{
  const nav=document.querySelector("#admin-navigation");
  return {sh:nav.scrollHeight, ch:nav.clientHeight, w:nav.offsetWidth, groupsExpanded:nav.querySelectorAll("button[aria-expanded='true']").length, groupsCollapsed:nav.querySelectorAll("button[aria-expanded='false']").length};
});
console.log("initial", JSON.stringify(state), "collapsedCount", collapsedCount);
const frame=await page.evaluate(()=>{const n=document.querySelector("#admin-navigation"); const f=n.closest("div.sticky")||n.parentElement; const r=f.getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height};});
await page.screenshot({path:path.join(OUT,"sidebar-initial.png"),clip:{x:frame.x,y:frame.y,width:frame.width,height:frame.height}});
await page.evaluate(()=>{const nav=document.querySelector("#admin-navigation");[...nav.querySelectorAll("button[aria-expanded='false']")].forEach(b=>b.click());});
await new Promise(r=>setTimeout(r,700));
await page.evaluate(()=>{const n=document.querySelector("#admin-navigation"); n.scrollTop=Math.round((n.scrollHeight-n.clientHeight)/2);});
await new Promise(r=>setTimeout(r,500));
await page.mouse.move(frame.x+frame.width-8, frame.y+300);
await new Promise(r=>setTimeout(r,500));
await page.screenshot({path:path.join(OUT,"sidebar-expanded-all-mid.png"),clip:{x:frame.x,y:frame.y,width:frame.width,height:frame.height}});
await page.evaluate(()=>{const n=document.querySelector("#admin-navigation"); n.scrollTop=n.scrollHeight;});
await new Promise(r=>setTimeout(r,500));
await page.screenshot({path:path.join(OUT,"sidebar-expanded-all-end.png"),clip:{x:frame.x,y:frame.y,width:frame.width,height:frame.height}});
console.log("after expand", JSON.stringify(await page.evaluate(()=>{const n=document.querySelector("#admin-navigation"); return {sh:n.scrollHeight, ch:n.clientHeight, gutter:n.offsetWidth-n.clientWidth};})));
await browser.close();
